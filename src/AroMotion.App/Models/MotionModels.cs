using System.Collections.ObjectModel;
using System.Text.Json.Serialization;

namespace AroMotion.App.Models;

public sealed class Motion3DSegment
{
    public Guid Id { get; init; } = Guid.NewGuid();
    public long StartMs { get; set; }
    public long EndMs { get; set; }
    public string Preset { get; set; } = "Focus";
    public double RotateX { get; set; }
    public double RotateY { get; set; }
    public double RotateZ { get; set; }
    public double Depth { get; set; }
    public double PanX { get; set; }
    public double PanY { get; set; }
    public double Perspective { get; set; } = 1.0;
    public double Speed { get; set; } = 1.0;
    public double Intensity { get; set; } = 1.0;
    public long HoldMs { get; set; } = 650;
    public string Easing { get; set; } = "cubic-in-out";
    public bool Shadow { get; set; } = true;
    public bool Reflection { get; set; }
    public bool AutoGenerated { get; set; }
    public bool Enabled { get; set; } = true;
}

