    public string RightClickColor { get; set; } = "#FF5D8F";
    public int ClickAnimationMs { get; set; } = 420;
    public string? ClickSoundPath { get; set; }
    public bool ClickSoundEnabled { get; set; } = true;
    public double MotionBlur { get; set; } = 0.25;
    public bool SmoothCursor { get; set; } = true;
